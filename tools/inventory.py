def write_text_lf(path: Path, text: str) -> None:
    """Write UTF-8 with LF regardless of platform, so CI and Windows agree."""
    with path.open('w', encoding='utf-8', newline='\n') as handle:
        handle.write(text)


def write_outputs() -> list[dict]:
    rows = build_rows()
    kept, collapsed_rows = collapsed(rows)
    OUT_CSV.write_bytes(render_csv(rows))
    write_text_lf(OUT_MD, render_md(rows, kept, collapsed_rows))
    write_text_lf(OUT_HTML, render_html(rows))
    return rows


def check_outputs() -> list[str]:
    rows = build_rows()
    kept, collapsed_rows = collapsed(rows)
    expected = {
        OUT_CSV: render_csv(rows),
        OUT_MD: render_md(rows, kept, collapsed_rows).encode('utf-8'),
        OUT_HTML: render_html(rows).encode('utf-8'),
    }
    problems = []
    for path, payload in expected.items():
        if not path.exists():
            problems.append(f'missing: {path.relative_to(ROOT)}')
        elif path.read_bytes() != payload:
            problems.append(f'stale: {path.relative_to(ROOT)}')
    return problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true', help='regenerate docs/INVENTORY.md, inventory.csv, inventory.html')
    parser.add_argument('--check', action='store_true', help='exit 1 when the generated documents are stale')
    parser.add_argument('--stats', action='store_true', help='print a JSON summary of areas and kinds')
    args = parser.parse_args(argv)
    if args.write:
        rows = write_outputs()
        print(f'wrote {len(rows)} rows to docs/INVENTORY.md, docs/inventory.csv, docs/inventory.html')
        return 0
    if args.check:
        problems = check_outputs()
        for problem in problems:
            print('STALE: ' + problem, file=sys.stderr)
        if problems:
            print('Run: python tools/inventory.py --write', file=sys.stderr)
            return 1
        print('inventory OK')
        return 0
    if args.stats:
        rows = build_rows()
        areas: dict[str, int] = {}
        kinds: dict[str, int] = {}
        for row in rows:
            areas[row['area']] = areas.get(row['area'], 0) + 1
            kinds[row['kind']] = kinds.get(row['kind'], 0) + 1
        print(json.dumps({'files': len(rows), 'areas': areas, 'kinds': kinds},
                         ensure_ascii=False, indent=2))
        return 0
    parser.print_help()
    return 0


if __name__ == '__main__':
    raise SystemExit(main())