def py_kind(path: Path) -> str:
    try:
        source = path.read_text(encoding='utf-8', errors='replace')
    except OSError:
        return KIND_LIB
    if path.name.startswith('test_') or 'unittest' in source:
        return KIND_TEST
    return KIND_TOOL if any(marker in source for marker in CLI_MARKERS) else KIND_LIB


def clean(text: str, limit: int = 150) -> str:
    text = re.sub(r'!\[[^\]]*\]\([^)]*\)', '', text)
    text = re.sub(r'\[([^\]]+)\]\([^)]*\)', r'\1', text)
    text = re.sub(r'[`*_>#|]', '', text)
    text = re.sub(r'\s+', ' ', text).strip(' -:：')
    return text if len(text) <= limit else text[: limit - 1].rstrip() + '…'


def md_description(path: Path) -> str:
    try:
        raw = path.read_text(encoding='utf-8', errors='replace')
    except OSError:
        return ''
    if raw.startswith('---'):
        parts = raw.split('---', 2)
        if len(parts) == 3:
            raw = parts[2]
    heading, paragraph = '', ''
    in_code = False
    for line in raw.splitlines():
        stripped = line.strip()
        if stripped.startswith('```'):
            in_code = not in_code
            continue
        if in_code or not stripped:
            continue
        if not heading and stripped.startswith('#'):
            heading = stripped.lstrip('#').strip()
            continue
        if stripped.startswith(('|', '-', '*', '>', '1.', '2.', '3.')):
            continue
        paragraph = stripped
        break
    text = clean(paragraph or heading)
    if heading and paragraph and heading not in paragraph:
        text = f'{clean(heading, 60)}：{text}'
    return text


def py_description(path: Path) -> str:
    try:
        tree = ast.parse(path.read_text(encoding='utf-8', errors='replace'))
    except (OSError, SyntaxError):
        return ''
    doc = ast.get_docstring(tree) or ''
    if not doc:
        return ''
    first = ''
    for line in doc.strip().splitlines():
        line = line.strip()
        if line and not line.startswith(('Usage:', 'Args', 'Returns')):
            first = line
            break
    first = re.sub(r'^[\w./-]+\.py\s*[—:-]\s*', '', first)
    return clean(first)


def description(rel: str, path: Path) -> str:
    if rel in CURATED:
        return CURATED[rel][1]
    suffix = path.suffix.lower()
    if suffix == '.md':
        text = md_description(path)
    elif suffix == '.py':
        text = py_description(path)
    elif suffix in ('.json', '.yaml', '.yml', '.toml'):
        text = ''
    else:
        text = ''
    if '/ars/' in rel and not text:
        text = '上游 ARS 框架文件'
    if '/ooxml/schemas/' in rel and not text:
        text = 'OOXML 架构定义（ISO/IEC 29500）'
    return text or f'{kind_of(rel, path)}文件'


def flags(rel: str, path: Path) -> tuple[bool, bool, bool]:
    """(entry, runtime, network_or_writes) — coarse, documented in the output."""
    entry = kind_of(rel, path) in (KIND_ENTRY, KIND_CAPS, KIND_MODULE, KIND_DOC, KIND_INDEX, KIND_INSTALLER)
    runtime = False
    network = False
    writes = False
    if path.suffix == '.py':
        try:
            source = path.read_text(encoding='utf-8', errors='replace')
        except OSError:
            source = ''
        runtime = 'if __name__' in source
        network = any(marker in source for marker in NETWORK_MARKERS)
        writes = any(marker in source for marker in WRITE_MARKERS)
    elif path.suffix in ('.cmd', '.sh', '.ps1'):
        runtime = True
    return entry, runtime, network or writes


def build_rows() -> list[dict]:
    rows = []
    for rel, path in iter_files():
        entry, runtime, side = flags(rel, path)
        rows.append({
            'path': rel,
            'area': area_of(rel),
            'kind': kind_of(rel, path),
            'entry': 'yes' if entry else '',
            'runs': 'yes' if runtime else '',
            'side_effects': 'network/write' if side else '',
            'description': description(rel, path),
        })
    return rows


def collapsed(rows: list[dict]) -> tuple[list[dict], list[dict]]:
    collapsed_rows, kept = [], []
    buckets: dict[str, list[dict]] = {}
    for row in rows:
        for prefix, purpose in COLLAPSE.items():
            if row['path'].startswith(prefix):
                buckets.setdefault(prefix, []).append(row)
                break
        else:
            kept.append(row)
    for prefix, purpose in COLLAPSE.items():
        items = buckets.get(prefix, [])
        if not items:
            continue
        collapsed_rows.append({
            'path': prefix + '**',
            'area': items[0]['area'],
            'kind': KIND_UPSTREAM,
            'entry': '',
            'runs': '',
            'side_effects': '',
            'description': f'{len(items)} 个文件：{purpose}',
            'count': len(items),
        })
    return kept, collapsed_rows


def render_csv(rows: list[dict]) -> bytes:
    buffer = io.StringIO()
    writer = csv.writer(buffer, lineterminator='\n')
    writer.writerow(['path', 'area', 'kind', 'is_entry', 'runs', 'side_effects', 'description'])
    for row in rows:
        writer.writerow([row['path'], row['area'], row['kind'], row['entry'],
                         row['runs'], row['side_effects'], row['description']])
    return buffer.getvalue().encode('utf-8-sig')


def normalized_size(path: Path) -> int:
    """LF-normalised byte length, so the summary does not depend on checkout EOL."""
    raw = path.read_bytes()
    if b'\x00' in raw:
        return len(raw)
    try:
        raw.decode('utf-8')
    except UnicodeDecodeError:
        return len(raw)
    return len(raw.replace(b'\r\n', b'\n'))


